"""A simple addition app."""

# Creation and Initialization of variables
num1 = 10
num2 = 5

# Data Processing: Execution of addition
total = num1 + num2

# Data Output: Result printing
print("The addition of", num1, "and", num2, "is:", total)
print(f"The sum of {num1} and {num2} is: {total} ")         # f-string formatting